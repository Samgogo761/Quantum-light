def peak_working_set_bytes() -> int:
    """Return the current process peak working set on Windows, or zero elsewhere."""
    if os.name != "nt":
        return 0
    import ctypes

    class MemoryCounters(ctypes.Structure):
        _fields_ = [("cb", ctypes.c_ulong), ("PageFaultCount", ctypes.c_ulong),
                    ("PeakWorkingSetSize", ctypes.c_size_t), ("WorkingSetSize", ctypes.c_size_t)] + [
            (name, ctypes.c_size_t) for name in ["QuotaPeakPagedPoolUsage", "QuotaPagedPoolUsage",
                                                    "QuotaPeakNonPagedPoolUsage", "QuotaNonPagedPoolUsage", "PagefileUsage",
                                                    "PeakPagefileUsage"]
        ]

    counters = MemoryCounters()
    counters.cb = ctypes.sizeof(counters)
    process = ctypes.windll.kernel32.GetCurrentProcess()
    function = ctypes.windll.kernel32.K32GetProcessMemoryInfo
    function.argtypes = [ctypes.c_void_p, ctypes.POINTER(MemoryCounters), ctypes.c_ulong]
    function.restype = ctypes.c_int
    if not function(process, ctypes.byref(counters), counters.cb):
        return 0
    return int(counters.PeakWorkingSetSize)


def csv_new(path: Path, header: list[str], rows: list[list[Any]]) -> None:
    """Write a new UTF-8 CSV with full floating-point precision."""
    with path.open("x", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(rows)


def source_hashes() -> dict[str, str]:
    """Hash every active source file, including uncommitted changes."""
    paths = [Path(__file__), BASE / "scripts/run_solo_v1.py", BASE / "src/ql_tip_1d/core.py",
             BASE / "src/ql_tip_1d/bias_v1.py", BASE / "src/ql_tip_1d/spectrum_v1.py",
             BASE / "configs/protocol_v1.json"]
    return {str(path.relative_to(BASE)).replace("\\", "/"): sha256(path) for path in paths}


def propagate_segment(
    psi: np.ndarray,
    grid: Any,
    start_fs: float,
    end_fs: float,
    dt_target_au: float,
    potential_at_midpoint: Any,
    cap_left: np.ndarray,
    cap_right: np.ndarray,
    detector_index: int,
    losses: np.ndarray,
    flux: float,
    trace_rows: list[list[Any]],
    initial_prep_losses: tuple[float, float],
    trace_interval_fs: float,
    deadline_seconds: float,
    start_clock: float,
    reuse_static_factorization: bool = False,
) -> tuple[np.ndarray, float, float, int]:
    """Propagate one segment with exact midpoint CAP/current bookkeeping."""
    duration_au = (end_fs - start_fs) / TAU_FS
    steps = int(np.ceil(duration_au / dt_target_au))
    dt = duration_au / steps
    first_potential = potential_at_midpoint(start_fs)
    cn = CrankNicolson(grid, dt, first_potential)
    next_trace = start_fs
    for step in range(steps + 1):
        time_fs = start_fs + step * dt * TAU_FS
        if time_fs + 1e-9 >= next_trace or step == steps:
            losses_now = losses.copy()
            residual = norm(psi, grid.dx_au) + sum(initial_prep_losses) + float(losses_now.sum()) - 1.0
            right_population = float(np.sum(np.abs(psi[grid.x_nm >= 4.0]) ** 2) * grid.dx_au)
            trace_rows.append([f"{time_fs:.17g}", f"{norm(psi, grid.dx_au):.17g}", f"{right_population:.17g}",
                               f"{flux:.17g}", f"{losses_now[0]:.17g}", f"{losses_now[1]:.17g}", f"{residual:.17g}"])
            next_trace = time_fs + trace_interval_fs
        if step == steps:
            break
        if time.perf_counter() - start_clock > deadline_seconds:
            raise TimeoutError("Single-run 90-minute scientific compute limit reached")
        midpoint_fs = start_fs + (step + 0.5) * dt * TAU_FS
        if reuse_static_factorization:
            # Static segments reuse the LU factorisation; this changes no
            # arithmetic, only removes a repeated identical factorisation.
            after = cn.step(psi)
        else:
            after = cn.step(psi, potential_at_midpoint(midpoint_fs))
        midpoint = 0.5 * (psi + after)
        density = np.abs(midpoint) ** 2
        losses += 2.0 * dt * grid.dx_au * np.array([np.dot(cap_left, density), np.dot(cap_right, density)])
        flux += float(dt * np.imag(np.conj(midpoint[detector_index - 1]) * midpoint[detector_index]) / grid.dx_au)
        psi = after
    return psi, flux, dt, steps


def spectrum_for_state(
    run_id: str,
    label: str,
    psi: np.ndarray,
    grid: Any,
    diag: np.ndarray,
    off: np.ndarray,
    config: dict[str, Any],
    output_dir: Path,
    eta_eV: float,
    step_eV: float,
    mask_bounds_nm: tuple[float, float],
) -> dict[str, Any]:
    """Calculate and save one absolute total-static-energy spectrum."""
    mask = right_mask(grid, *mask_bounds_nm)
    phi = mask * psi
    energies = energy_grid_ev(config, float(config["I_over_mu"]), step_eV)
    spectrum = window_spectrum(diag, off, phi, grid.dx_au, energies, eta_eV)
    u_infinity = -float(config["F_dc_V_per_nm"]) * float(config["protocol"]["model"]["L_dc_nm"])
    write_spectrum_csv(output_dir / f"spectrum_{label}.csv", run_id, energies, spectrum, eta_eV, u_infinity)
    e_star = float(config["protocol"]["spectrum"]["E_star_eV"])
    offset = max(0.1 * e_star, float(config["protocol"]["spectrum"]["eta_base_eV"]))
    yields = {f"Y_H_{suffix}": integrate_above(energies, spectrum, e_star + sign * offset)
              for suffix, sign in [("lower", -1.0), ("main", 0.0), ("upper", 1.0)]}
    masked_norm = norm(phi, grid.dx_au)
    integral = float(np.trapezoid(spectrum, energies))
    return {
        "label": label,
        "eta_eV": eta_eV,
        "energy_step_eV": step_eV,
        "mask_bounds_nm": list(mask_bounds_nm),
        "energy_range_eV": [float(energies[0]), float(energies[-1])],
        "energy_points": len(energies),
        "masked_norm": masked_norm,
        "spectrum_integral": integral,
        "spectrum_norm_absolute_difference": abs(integral - masked_norm),
        **yields,
    }


def run_preparation(config: dict[str, Any], run_id: str, results: Path, raw: Path, start_clock: float) -> dict[str, Any]:
    """Prepare and cache one DC state without post-preparation renormalisation."""
    grid = make_grid(config)
    surface = surface_potential(grid.x_au, config["protocol"]["model"]["well_width_nm"],
                                config["protocol"]["model"]["well_depth_eV"])
    energies, states = bound_states(grid, surface, config["protocol"]["model"]["well_depth_eV"])
    if len(energies) != 1:
        raise RuntimeError("The no-DC initial well must have exactly one bound state")
    initial = states[:, 0].astype(complex)
    psi = initial.copy()
    cap_left, cap_right = cap_arrays(grid, config)
    dc = dc_potential_au(grid.x_au, float(config["F_dc_V_per_nm"]), config["protocol"]["model"]["L_dc_nm"])
    preparation = config["preparation"]
    prep_end = -100.0
    wait_start = prep_end - float(preparation["wait_duration_fs"])
    ramp_start = wait_start - float(preparation["ramp_duration_fs"])

    def potential(time_fs: float) -> np.ndarray:
        return surface + smootherstep(time_fs, ramp_start, wait_start) * dc - 1j * (cap_left + cap_right)

    losses = np.zeros(2)
    rows: list[list[Any]] = []
    detector_index = int(np.searchsorted(grid.x_nm, 10.0))
    psi, _, dt_ramp, steps_ramp = propagate_segment(
        psi, grid, ramp_start, wait_start, float(config["numerics"]["dt_au"]), potential, cap_left, cap_right,
        detector_index, losses, 0.0, rows, (0.0, 0.0), 0.5, 5400.0, start_clock)
    psi, _, dt_wait, steps_wait = propagate_segment(
        psi, grid, wait_start, prep_end, float(config["numerics"]["dt_au"]), potential, cap_left, cap_right,
        detector_index, losses, 0.0, rows, (0.0, 0.0), 0.5, 5400.0, start_clock,
        reuse_static_factorization=True)
    dt = dt_wait
    steps = steps_ramp + steps_wait
    prep_norm = norm(psi, grid.dx_au)
    residual = prep_norm + float(losses.sum()) - 1.0
    np.savez_compressed(raw / "state_prep.npz", x_au=grid.x_au, psi_initial=initial, psi_prep=psi,
                        surface_au=surface, dc_au=dc, left_CAP_au=cap_left, right_CAP_au=cap_right,
                        dx_au=grid.dx_au, units="atomic units; psi=bohr^(-1/2)")
    csv_new(results / "trace.csv", ["t_fs", "norm", "right_population", "signed_flux_integral", "left_CAP_loss",
                                    "right_CAP_loss", "probability_budget_residual"], rows)
    return {
        "run_kind": "preparation", "status": "PASS" if abs(residual) <= 1e-8 else "FAIL",
        "initial_ground_energy_eV": float(energies[0] * EH_EV), "ramp_start_fs": ramp_start,
        "ramp_end_fs": wait_start, "prep_end_fs": prep_end, "actual_dt_au": dt, "steps": steps,
        "N_initial": 1.0, "N_prep": prep_norm, "left_CAP_loss_prep": float(losses[0]),
        "right_CAP_loss_prep": float(losses[1]), "pre_laser_population_loss": float(losses.sum()),
        "max_probability_budget_residual": max(abs(float(row[-1])) for row in rows),
        "state_prep_path": str((raw / "state_prep.npz").relative_to(BASE)).replace("\\", "/"),
    }


def run_observation(config: dict[str, Any], run_id: str, results: Path, raw: Path, start_clock: float) -> dict[str, Any]:
    """Reuse a verified preparation, propagate DC-only or laser, and read H_dc spectra."""
    prep_path = BASE / config["prep_state_path"]
    prep_summary_path = BASE / config["prep_summary_path"]
    prep_summary = json.loads(prep_summary_path.read_text(encoding="utf-8"))
    if prep_summary.get("status") != "PASS":
        raise ValueError("The preparation cache is not PASS")
    expected_prep_hash = config.get("prep_state_sha256")
    if expected_prep_hash and sha256(prep_path) != expected_prep_hash:
        raise ValueError("Preparation state hash mismatch")
    with np.load(prep_path) as saved:
        x_au = saved["x_au"]
        psi = saved["psi_prep"].astype(complex)
        psi_prep = psi.copy()
        initial = saved["psi_initial"].astype(complex)
        cap_left = saved["left_CAP_au"]
        cap_right = saved["right_CAP_au"]
        dx_au = float(saved["dx_au"])
    grid = make_grid(config)
    if len(grid.x_au) != len(x_au) or not np.allclose(grid.x_au, x_au, rtol=0.0, atol=1e-13):
        raise ValueError("Preparation and observation grids differ")
    if abs(grid.dx_au - dx_au) > 1e-13:
        raise ValueError("Preparation and observation dx differ")
    surface = surface_potential(grid.x_au, config["protocol"]["model"]["well_width_nm"],
                                config["protocol"]["model"]["well_depth_eV"])
    static = static_potential_au(grid, config)
    cap = cap_left + cap_right
    is_laser = config["run_kind"] == "laser"
    optical_spatial = integrated_near_field(
        grid.x_au, ell_nm=float(config["protocol"]["model"]["ell_nm"])) if is_laser else None

    def potential(time_fs: float) -> np.ndarray:
        optical = optical_potential_au(grid, config, time_fs, spatial=optical_spatial) if is_laser and abs(time_fs) <= 100.0 else 0.0
        return static + optical - 1j * cap

    losses = np.zeros(2)
    prep_losses = (float(prep_summary["left_CAP_loss_prep"]), float(prep_summary["right_CAP_loss_prep"]))
    rows: list[list[Any]] = []
    detector_index = int(np.searchsorted(grid.x_nm, 10.0))
    propagation_start = time.perf_counter()
    psi, flux, dt_main, steps_main = propagate_segment(
        psi, grid, -100.0, 100.0, float(config["numerics"]["dt_au"]), potential, cap_left, cap_right,
        detector_index, losses, 0.0, rows, prep_losses, 0.5, 5400.0, start_clock,
        reuse_static_factorization=not is_laser)
    state_100 = psi.copy()
    losses_100 = losses.copy()
    flux_100 = flux
    dt_late = None
    steps_late = 0
    if config.get("late_readout", True):
        psi, flux, dt_late, steps_late = propagate_segment(
            psi, grid, 100.0, 125.0, float(config["numerics"]["dt_au"]), potential, cap_left, cap_right,
            detector_index, losses, flux, rows, prep_losses, 0.5, 5400.0, start_clock,
            reuse_static_factorization=not is_laser)
    propagation_seconds = time.perf_counter() - propagation_start
    np.savez_compressed(raw / "state_100fs.npz", x_au=grid.x_au, psi_initial=initial, psi_prep=psi_prep,
                        psi=state_100, static_H_potential_au=static, left_CAP_au=cap_left, right_CAP_au=cap_right,
                        dx_au=grid.dx_au, readout_fs=100.0, units="atomic units; psi=bohr^(-1/2)")
    if config.get("late_readout", True):
        np.savez_compressed(raw / "state_125fs.npz", x_au=grid.x_au, psi_initial=initial, psi_prep=psi_prep,
                            psi=psi, static_H_potential_au=static, left_CAP_au=cap_left, right_CAP_au=cap_right,
                            dx_au=grid.dx_au, readout_fs=125.0, units="atomic units; psi=bohr^(-1/2)")
    csv_new(results / "trace.csv", ["t_fs", "norm", "right_population", "signed_flux_integral", "left_CAP_loss",
                                    "right_CAP_loss", "probability_budget_residual"], rows)
    diag, off = hamiltonian_diagonals(grid, static)
    spectrum_start = time.perf_counter()
    spectra = []
    # eta=.2 was the frozen starting value, but P1 showed 5.7-7.6% changes
    # versus eta=.1.  The additional eta=.05 post-processing then bounded the
    # eta=.1 residual at 1.8-3.4%, so eta=.1/dE=.025 becomes the production
    # resolution while every original eta=.2 spectrum remains saved.
    spectrum_jobs = [("t100_eta0p1_dE0p025_mask2to4", state_100, 0.1, 0.025, (2.0, 4.0))]
    if config.get("full_spectrum_controls", False):
        spectrum_jobs.extend([
            ("t100_eta0p2_dE0p05_mask2to4", state_100, 0.2, 0.05, (2.0, 4.0)),
            ("t100_eta0p1_dE0p025_mask3to5", state_100, 0.1, 0.025, (3.0, 5.0)),
            ("t125_eta0p1_dE0p025_mask2to4", psi, 0.1, 0.025, (2.0, 4.0)),
        ])
    for label, state, eta, step, mask_bounds in spectrum_jobs:
        spectra.append(spectrum_for_state(run_id, label, state, grid, diag, off, config, results, eta, step, mask_bounds))
    spectrum_seconds = time.perf_counter() - spectrum_start
    main = spectra[0]
    return {
        "run_kind": config["run_kind"], "status": "PASS",
        "N_prep": prep_summary["N_prep"], "left_CAP_loss_prep": prep_losses[0], "right_CAP_loss_prep": prep_losses[1],
        "N_100fs": norm(state_100, grid.dx_au), "N_125fs": norm(psi, grid.dx_au),
        "left_CAP_loss_observation_100fs": float(losses_100[0]), "right_CAP_loss_observation_100fs": float(losses_100[1]),
        "left_CAP_loss_total_125fs": float(prep_losses[0] + losses[0]), "right_CAP_loss_total_125fs": float(prep_losses[1] + losses[1]),
        "signed_flux_100fs": flux_100, "signed_flux_125fs": flux,
        "actual_dt_au_main": dt_main, "actual_dt_au_late": dt_late, "steps_main": steps_main, "steps_late": steps_late,
        "max_probability_budget_residual": max(abs(float(row[-1])) for row in rows),
        "Y_H": main["Y_H_main"], "Y_H_lower": main["Y_H_lower"], "Y_H_upper": main["Y_H_upper"],
        "masked_norm": main["masked_norm"], "spectrum_integral": main["spectrum_integral"],
        "propagation_seconds": propagation_seconds, "spectrum_seconds": spectrum_seconds, "spectra": spectra,
    }


def main() -> int:
    """Run one configuration and preserve success or failure provenance."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--run-id", required=True)
    args = parser.parse_args()
    config = json.loads(args.config.read_text(encoding="utf-8"))
    results = BASE / "results/bias_v1" / args.run_id
    raw = BASE / "data/raw/bias_v1" / args.run_id
    results.mkdir(parents=True, exist_ok=False)
    raw.mkdir(parents=True, exist_ok=False)
    start_clock = time.perf_counter()
    started = datetime.now(timezone.utc).isoformat()
    write_json_new(results / "config.json", config)
    provenance = {
        "run_id": args.run_id, "started_utc": started, "config_sha256": sha256(args.config),
        "base_git_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=BASE, text=True).strip(),
        "source_sha256": source_hashes(), "python": sys.version, "numpy": np.__version__, "scipy": scipy.__version__,
        "platform": platform.platform(), "processor": platform.processor(), "device": "CPU", "dtype": "complex128",
        "renormalization_during_or_after_preparation": False, "exit_status": "RUNNING",
    }
    write_json_new(results / "provenance.json", provenance)
    try:
        if config["run_kind"] == "preparation":
            summary = run_preparation(config, args.run_id, results, raw, start_clock)
        elif config["run_kind"] in {"laser", "dc-only"}:
            summary = run_observation(config, args.run_id, results, raw, start_clock)
        else:
            raise ValueError(f"Unknown run_kind: {config['run_kind']}")
        summary.update({
            "run_id": args.run_id, "F_dc_V_per_nm": config["F_dc_V_per_nm"],
            "I_apex_W_per_cm2": config["I_apex_W_per_cm2"], "I_inc_W_per_cm2": config["I_apex_W_per_cm2"] / 9.0,
            "CEP_rad": config["CEP_rad"], "well_cells": config["numerics"]["well_cells"],
            "dx_nm": config["protocol"]["model"]["well_width_nm"] / config["numerics"]["well_cells"],
            "xmax_nm": config["numerics"]["xmax_nm"],
            "readout_fs": [100.0, 125.0] if config.get("late_readout", True) else [100.0],
            "wall_seconds": time.perf_counter() - start_clock, "peak_working_set_bytes": peak_working_set_bytes(),
        })
        if summary["max_probability_budget_residual"] > float(config["protocol"]["numerics"]["probability_budget_max_residual"]):
            summary["status"] = "FAIL"
            summary["failure_reason"] = "Discrete probability budget residual exceeds protocol tolerance"
        write_json_new(results / "summary.json", summary)
        provenance["exit_status"] = summary["status"]
        provenance["finished_utc"] = datetime.now(timezone.utc).isoformat()
        (results / "provenance.json").write_text(json.dumps(provenance, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (results / "run_log.txt").write_text(f"run_id={args.run_id}\ncommand={sys.argv}\nstarted_utc={started}\n"
                                               f"finished_utc={provenance['finished_utc']}\nstatus={summary['status']}\n"
                                               f"wall_seconds={summary['wall_seconds']:.17g}\n", encoding="utf-8")
        print(json.dumps(summary, indent=2, ensure_ascii=False))
        return 0 if summary["status"] == "PASS" else 2
    except Exception as error:
        finished = datetime.now(timezone.utc).isoformat()
        failure = {"run_id": args.run_id, "status": "FAIL", "error_type": type(error).__name__,
                   "error": str(error), "traceback": traceback.format_exc(), "started_utc": started,
                   "finished_utc": finished, "wall_seconds": time.perf_counter() - start_clock,
                   "peak_working_set_bytes": peak_working_set_bytes()}
        write_json_new(results / "failure.json", failure)
        (results / "run_log.txt").write_text(f"run_id={args.run_id}\nstatus=FAIL\n{traceback.format_exc()}\n", encoding="utf-8")
        raise


if __name__ == "__main__":
    raise SystemExit(main())
